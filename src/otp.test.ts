import { afterEach, beforeEach, describe, expect, spyOn, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { matchesOtp, verifyOtp } from './otp'

// Public RFC 6238 SHA-1 test vector, not a real authenticator secret.
const SECRET = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ'
const originalSecret = process.env.FAUCET_TOTP_SECRET
const originalState = process.env.FAUCET_STATE_FILE
let directory: string
let clock: ReturnType<typeof spyOn<typeof Date, 'now'>>

beforeEach(() => {
  const scratch = join(import.meta.dir, '..', '.scratch')
  mkdirSync(scratch, { recursive: true })
  directory = mkdtempSync(join(scratch, 'otp-'))
  process.env.FAUCET_STATE_FILE = join(directory, 'state.json')
  process.env.FAUCET_TOTP_SECRET = SECRET
  clock = spyOn(Date, 'now').mockReturnValue(59_000)
})

afterEach(() => {
  clock.mockRestore()
  if (originalSecret === undefined) delete process.env.FAUCET_TOTP_SECRET
  else process.env.FAUCET_TOTP_SECRET = originalSecret
  if (originalState === undefined) delete process.env.FAUCET_STATE_FILE
  else process.env.FAUCET_STATE_FILE = originalState
  rmSync(directory, { recursive: true, force: true })
})

describe('OTP compatibility', () => {
  test('accepts the RFC token once, including whitespace normalization', () => {
    expect(verifyOtp('287 082')).toEqual({ ok: true })
    expect(verifyOtp('287082')).toEqual({ ok: false, reason: 'replayed' })
  })

  test('allows one time step of drift in either direction', () => {
    for (const epoch of [0, 29, 59, 89]) {
      clock.mockReturnValue(epoch * 1000)
      expect(matchesOtp('287082', SECRET)).toBe(true)
    }
    for (const epoch of [90, 119]) {
      clock.mockReturnValue(epoch * 1000)
      expect(matchesOtp('287082', SECRET)).toBe(false)
    }
  })

  test('keeps 10-byte secrets generated by v12 usable', () => {
    // SHA-1 TOTP for this public 10-byte fixture at Unix time 59.
    expect(matchesOtp('996554', 'JBSWY3DPEHPK3PXP')).toBe(true)
  })

  test('rejects missing, malformed and incorrect codes', () => {
    expect(verifyOtp(undefined)).toEqual({ ok: false, reason: 'invalid' })
    expect(verifyOtp('abcdef')).toEqual({ ok: false, reason: 'malformed' })
    expect(verifyOtp('000000')).toEqual({ ok: false, reason: 'invalid' })
  })

  test('reports a missing secret', () => {
    delete process.env.FAUCET_TOTP_SECRET
    expect(verifyOtp('287082')).toEqual({ ok: false, reason: 'missing_secret' })
  })
})
